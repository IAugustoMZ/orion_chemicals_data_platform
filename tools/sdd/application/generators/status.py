"""Generator of the status board: where every spec is in the lifecycle.

Application layer. Produces the ``status`` block of the root `README.md` and the whole
`specs/README.md`. Both are computed from the dossiers, so the front page never lies about
progress (documentation-standard.md, "generated sections").
"""

from __future__ import annotations

from sdd.application.generators import GeneratedFile
from sdd.application.use_cases.evaluate_dossier import DossierReport, EvaluateDossier
from sdd.domain.dossier import Dossier
from sdd.domain.gate_status import GateState
from sdd.domain.gates import GATES

SYMBOLS: dict[GateState, str] = {
    GateState.PASSED: "✅",
    GateState.PARTIAL: "🟡",
    GateState.PENDING: "⚪",
    GateState.STALE: "🟠",
    GateState.FAILED: "❌",
    GateState.BLOCKED: "⏸️",
}
"""One symbol per gate state, explained by `LEGEND`."""

LEGEND = (
    "✅ passed · 🟡 partly approved · ⚪ pending · 🟠 stale (changed after approval) · "
    "❌ failed · ⏸️ blocked by an earlier gate"
)


def where_it_is(report: DossierReport) -> str:
    """Return the phase and gate a dossier is at, e.g. ``Discover (G1)``.

    Args:
        report: the evaluated dossier.
    """
    current = report.current
    return f"{current.gate.phase_name} ({current.gate.id})" if current else "done: released"


def kind_label(dossier: Dossier) -> str:
    """Return the kind shown on the board; work outside the catalogue is marked as such.

    Args:
        dossier: the dossier.
    """
    return "feature (outside RTs)" if dossier.outside_catalogue else dossier.kind.value


def render_board(reports: tuple[DossierReport, ...], link_prefix: str) -> str:
    """Render the status table of every dossier.

    Args:
        reports: the evaluated dossiers.
        link_prefix: path from the target document to `specs/` ("specs/" or "").

    Returns:
        Markdown: a table with one row per dossier, or a sentence when there is none.
    """
    if not reports:
        return "_No spec yet. Start one with `poetry run sdd new`._"
    gate_ids = " | ".join(gate.id.value for gate in GATES)
    rows = [
        f"| Spec | Kind | Where it is | {gate_ids} | Guide |",
        "|---|---|---|" + "---|" * len(GATES) + "---|",
    ]
    for report in reports:
        dossier, folder = report.dossier, f"{link_prefix}{report.dossier.folder_name}"
        chips = " | ".join(SYMBOLS[status.state] for status in report.statuses)
        rows.append(
            f"| [{dossier.id} · {dossier.title}]({folder}/prd.md) | {kind_label(dossier)} "
            f"| {where_it_is(report)} | {chips} | [📘]({folder}/teaching-guide.md) |"
        )
    return "\n".join(rows) + f"\n\n{LEGEND}"


class StatusGenerator:
    """Generate the README status block and the specs index."""

    def __init__(self, evaluator: EvaluateDossier) -> None:
        """Receive the evaluator the board is computed from.

        Args:
            evaluator: evaluates every dossier.
        """
        self._evaluator = evaluator

    def generate(self) -> tuple[GeneratedFile, ...]:
        """Return the README block and the full `specs/README.md`."""
        reports = self._evaluator.all()
        index = "\n".join(
            (
                "# Specs",
                "",
                "<!-- GENERATED by `sdd sync` from the dossiers. Do not edit by hand. -->",
                "",
                "Every piece of work is a *dossier*: one folder with one artifact per phase of "
                "the lifecycle ([how it works](../harness/how-it-works.md)). Start one with "
                "`poetry run sdd new`; see where each one is below.",
                "",
                render_board(reports, ""),
                "",
            )
        )
        return (
            GeneratedFile("README.md", render_board(reports, "specs/"), block="status"),
            GeneratedFile("specs/README.md", index),
        )

    def owned_prefixes(self) -> tuple[str, ...]:
        """Return nothing: the generated files live among hand-written ones."""
        return ()
