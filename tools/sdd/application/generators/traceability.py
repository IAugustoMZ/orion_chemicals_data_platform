"""Generator of the traceability matrix: RT -> dossiers -> how far each RT got.

Application layer. Produces `docs/requirements/traceability.md` and the coverage line of the
README. An RT's status comes from the most advanced *feature* dossier that cites it; enablers
only *support* RTs and never count as delivering them. Features that serve no RT are listed in
their own section, with their rationale (ADR-0014), so work outside the catalogue stays visible.
"""

from __future__ import annotations

from collections.abc import Mapping

from sdd.application.generators import GeneratedFile
from sdd.application.generators.status import where_it_is
from sdd.application.ports.reference_data import RequirementCatalog
from sdd.application.use_cases.evaluate_dossier import DossierReport, EvaluateDossier
from sdd.domain.dossier import DossierKind
from sdd.domain.gate_status import GateState
from sdd.domain.gates import GateId
from sdd.domain.requirement import Requirement

_LEVELS: tuple[tuple[GateId, str], ...] = (
    (GateId.G7, "validated"),
    (GateId.G6, "delivered"),
    (GateId.G4, "specified"),
)
_CITED = "in discovery"
_NONE = "not started"


def requirement_status(rt: str, reports: tuple[DossierReport, ...]) -> str:
    """Return how far a requirement got, judged by the feature dossiers that cite it.

    Args:
        rt: the RT id.
        reports: every evaluated dossier.
    """
    features = [
        r
        for r in reports
        if r.dossier.kind is DossierKind.FEATURE and rt in r.dossier.requirements
    ]
    for gate_id, label in _LEVELS:
        if any(r.status(gate_id).state is GateState.PASSED for r in features):
            return label
    return _CITED if features else _NONE


def coverage_line(rts: tuple[str, ...], reports: tuple[DossierReport, ...]) -> str:
    """Return a one-line summary: how many RTs reached each level.

    Args:
        rts: every RT id of the catalogue.
        reports: every evaluated dossier.
    """
    statuses = [requirement_status(rt, reports) for rt in rts]
    counts = {
        label: statuses.count(label) for label in (_CITED, "specified", "delivered", "validated")
    }
    parts = " · ".join(f"{label} **{count}**" for label, count in counts.items())
    return f"Requirements RT01-RT{len(rts):02d}: {parts} · not started **{statuses.count(_NONE)}**"


class TraceabilityGenerator:
    """Generate the traceability matrix and the README coverage line."""

    def __init__(self, evaluator: EvaluateDossier, requirements: RequirementCatalog) -> None:
        """Receive the evaluator and the catalogue.

        Args:
            evaluator: evaluates every dossier.
            requirements: the RT catalogue (statements and categories).
        """
        self._evaluator = evaluator
        self._requirements = requirements

    def generate(self) -> tuple[GeneratedFile, ...]:
        """Return the matrix document and the README coverage block."""
        reports = self._evaluator.all()
        catalog = self._requirements.all()
        rts = tuple(sorted(catalog))
        summary = coverage_line(rts, reports)
        readme = f"{summary}. [Full traceability matrix](docs/requirements/traceability.md)."
        return (
            GeneratedFile("README.md", readme, block="coverage"),
            GeneratedFile(
                "docs/requirements/traceability.md", self._matrix(catalog, reports, summary)
            ),
        )

    def owned_prefixes(self) -> tuple[str, ...]:
        """Return nothing: the generated files live among hand-written ones."""
        return ()

    def _matrix(
        self,
        catalog: Mapping[str, Requirement],
        reports: tuple[DossierReport, ...],
        summary: str,
    ) -> str:
        """Render the matrix, one section per catalogue category.

        Args:
            catalog: the RT catalogue by id.
            reports: every evaluated dossier.
            summary: the coverage line.
        """
        lines = [
            "# Requirements traceability",
            "",
            "<!-- GENERATED by `sdd sync` from rt-catalog.yaml and specs/. "
            "Do not edit by hand. -->",
            "",
            "Each technical requirement of the [catalogue](README.md), the dossiers that cite it "
            "and how far it got: *in discovery* (cited), *specified* (G4 passed), *delivered* "
            "(G6 passed), *validated* (G7 passed). Enablers support requirements but never "
            "deliver them.",
            "",
            summary + ".",
        ]
        for key, title in self._requirements.categories().items():
            lines += [
                "",
                f"## {title}",
                "",
                "| RT | Phase | First | Requirement | Specs | Status |",
            ]
            lines.append("|---|---|---|---|---|---|")
            for rt in sorted(r for r in catalog if catalog[r].category == key):
                requirement = catalog[rt]
                cited = [
                    f"[{r.dossier.id}](../../specs/{r.dossier.folder_name}/prd.md)"
                    + (" (enabler)" if r.dossier.kind is DossierKind.ENABLER else "")
                    for r in reports
                    if rt in r.dossier.requirements
                ]
                lines.append(
                    f"| {rt} | {requirement.phase.value} | {'★' if requirement.priority else ''} "
                    f"| {requirement.statement} | {', '.join(cited) or '—'} "
                    f"| {requirement_status(rt, reports)} |"
                )
        lines += ["", "★ = the catalogue asks to tackle this RT first (risk discovery).", ""]
        lines += _outside_catalogue(reports)
        return "\n".join(lines)


def _outside_catalogue(reports: tuple[DossierReport, ...]) -> list[str]:
    """Render the section of features that serve no RT, with why each one is worth doing.

    Args:
        reports: every evaluated dossier.
    """
    lines = [
        "## Work outside the catalogue",
        "",
        "Features that serve no RT (ADR-0014). Each one states why it is worth doing, and its "
        "PRD lists the RTs that were considered.",
        "",
    ]
    outside = [r for r in reports if r.dossier.outside_catalogue]
    if not outside:
        return [*lines, "_None._", ""]
    lines += ["| Spec | Why it is worth doing | Where it is |", "|---|---|---|"]
    for report in outside:
        dossier = report.dossier
        why = " ".join(dossier.rationale.split()).replace("|", "\\|") or "—"
        lines.append(
            f"| [{dossier.id} · {dossier.title}](../../specs/{dossier.folder_name}/prd.md) "
            f"| {why} | {where_it_is(report)} |"
        )
    return [*lines, ""]
