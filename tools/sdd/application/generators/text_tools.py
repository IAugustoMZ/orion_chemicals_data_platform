"""Small text helpers of the generators: front matter and marked blocks.

Application layer, pure functions. Front matter is the ``---``-delimited header of skills and
role files; only flat ``key: value`` pairs are supported, which is all our sources use (this
keeps the application layer free of a YAML dependency).
"""

from __future__ import annotations

import re

_FRONT_MATTER = re.compile(r"\A---\n(?P<head>.*?)\n---\n(?P<body>.*)\Z", re.DOTALL)


def split_front_matter(text: str) -> tuple[dict[str, str], str]:
    """Split a Markdown file into its front-matter fields and its body.

    Args:
        text: the file content (LF line endings).

    Returns:
        (fields, body). Without front matter, fields is empty and body is the whole text.
    """
    match = _FRONT_MATTER.match(text.replace("\r\n", "\n"))
    if not match:
        return {}, text
    fields: dict[str, str] = {}
    for line in match.group("head").splitlines():
        key, separator, value = line.partition(":")
        if separator and key.strip():
            fields[key.strip()] = value.strip().strip("\"'")
    return fields, match.group("body")


def render_front_matter(fields: dict[str, str]) -> str:
    """Render flat fields as a front-matter header (values double-quoted when needed).

    Args:
        fields: ordered key/value pairs.
    """
    lines = []
    for key, value in fields.items():
        needs_quotes = any(ch in value for ch in ":#") or value != value.strip()
        lines.append(f'{key}: "{value}"' if needs_quotes else f"{key}: {value}")
    return "---\n" + "\n".join(lines) + "\n---\n"


def replace_block(text: str, block: str, content: str) -> str | None:
    """Replace the content between the start and end markers of a block.

    Args:
        text: the whole document.
        block: the block name (``<!-- sdd:<block>:start -->``).
        content: the new content, placed between the markers on its own lines.

    Returns:
        The new document, or None when the markers are missing (the caller reports it).
    """
    start, end = f"<!-- sdd:{block}:start -->", f"<!-- sdd:{block}:end -->"
    head, found_start, rest = text.partition(start)
    _, found_end, tail = rest.partition(end)
    if not (found_start and found_end):
        return None
    return f"{head}{start}\n{content.strip()}\n{end}{tail}"


def generated_banner(source: str) -> str:
    """Return the HTML comment that marks a generated file and names its source.

    Args:
        source: repository-relative path of the canonical file.
    """
    return (
        f"<!-- GENERATED by `sdd sync` from {source}. Do not edit here: change the source "
        "and run `poetry run sdd sync`. -->\n"
    )
